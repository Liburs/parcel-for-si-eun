import assert from 'node:assert/strict';
import {normalize,number} from './sync-tracking.mjs';
const event=(time,city,country,status='InTransit')=>({time_iso:time,description:'Scan '+city,location:city,address:{country,city},stage:status});
const response=(status,events)=>({code:0,data:{accepted:[{number,track_info:{latest_status:{status},latest_event:events[0],tracking:{providers:[{events}]}}}]}});
const a=event('2026-11-25T10:00:00+08:00','上海','CN'),b=event('2026-11-26T10:00:00+09:00','인천','KR');
let d=normalize(response('InTransit',[a,b,a]));assert.equal(d.events.length,2);assert.equal(d.events[0].location,'인천');assert.equal(d.stage,'korea');assert.equal(d.location.nameKo,'인천');
d=normalize(response('Delivered',[b]));assert.equal(d.stage,'delivered');
d=normalize(response('NotFound',[]));assert.equal(d.state,'awaiting_data');assert.equal(d.location,null);
d=normalize(response('Exception',[a]));assert.equal(d.state,'attention');
assert.throws(()=>normalize({code:0,data:{accepted:[]}}));
assert.throws(()=>normalize({code:1,data:{accepted:[]}}));
console.log('PASS chronological events, deduplication, location, delivered, no data, exception, rejected response');
